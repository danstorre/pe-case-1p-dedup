"""Read the input CSV files. Nothing in this module writes to disk."""
import csv
from pathlib import Path

DATA_DIRECTORY = Path(__file__).parent.parent / "data"

TABLE_NAMES = [
    "profiles",
    "prospects",
    "prospect_aliases",
    "prospect_contacts",
    "sdr_follow_up_tasks",
    "power_dialer_call_logs",
    "email_activities",
    "prospect_contact_notes",
    "prospect_meetings",
]

# A company has at most 3 email slots (product rule).
EMAIL_FIELD_NAMES = ["email", "email_secondary", "email_tertiary"]


def load_tables(data_directory):
    """Read every input CSV into memory. Each row becomes a dict of column -> text."""
    tables = {}
    for table_name in TABLE_NAMES:
        csv_path = data_directory / f"{table_name}.csv"
        with open(csv_path, newline="", encoding="utf-8") as csv_file:
            tables[table_name] = list(csv.DictReader(csv_file))
    return tables
